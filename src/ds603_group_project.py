#Joint downside extreme analysis

gold = returns_common["gold_return"].dropna()
crude = returns_common["crude_return"].dropna()

# Align returns on the same dates
paired = pd.concat(
    [gold.rename("gold_return"), crude.rename("crude_return")],
    axis=1
).dropna()

# Define each market's bottom 5% threshold
gold_threshold = paired["gold_return"].quantile(0.05)
crude_threshold = paired["crude_return"].quantile(0.05)

# Identify downside extremes
gold_extreme = paired["gold_return"] <= gold_threshold
crude_extreme = paired["crude_return"] <= crude_threshold

# Probabilities
p_gold = gold_extreme.mean()
p_crude = crude_extreme.mean()
observed_joint = (gold_extreme & crude_extreme).mean()

# Joint probability under independence
expected_joint = p_gold * p_crude

print(f"Paired observations: {len(paired)}")
print(f"Gold 5th percentile threshold: {gold_threshold:.4f}%")
print(f"Crude 5th percentile threshold: {crude_threshold:.4f}%")
print(f"Gold downside extreme probability: {p_gold:.4%}")
print(f"Crude downside extreme probability: {p_crude:.4%}")
print(f"Observed joint downside probability: {observed_joint:.4%}")
print(f"Expected joint probability under independence: {expected_joint:.4%}")

if expected_joint > 0:
    print(f"Observed / expected joint probability: {observed_joint / expected_joint:.2f}")

"""How to interpret it
- Ratio above 1: joint downside extremes happened more often than the independence benchmark predicts.
- Ratio around 1: the observed frequency is close to the benchmark.
- Ratio below 1: joint downside extremes happened less often than expected under independence.
"""

from scipy.stats import fisher_exact

# Construct a 2x2 contingency table
contingency = pd.crosstab(
    gold_extreme.rename("Gold"),
    crude_extreme.rename("Crude")
).reindex(
    index=[False, True],
    columns=[False, True],
    fill_value=0
)

contingency.index = ["Gold not extreme", "Gold extreme"]
contingency.columns = ["Crude not extreme", "Crude extreme"]

print("Contingency table:")
display(contingency)

# Two-sided Fisher's exact test
odds_ratio, p_value = fisher_exact(
    contingency,
    alternative="two-sided"
)

print(f"Odds ratio: {odds_ratio:.4f}")
print(f"P-value: {p_value:.6f}")

if p_value < 0.05:
    print("Statistically significant association at the 5% level.")
else:
    print("No statistically significant association at the 5% level.")

"""Contingency Table & Fisher’s Exact Test (5th Percentile Extremes)

A $2 \times 2$ contingency table was constructed to evaluate the independence of 5th percentile downside extreme return days between Gold and Brent Crude across 6,492 common trading observations.
"""

# (a) Conditional probability, easier for a mixed audience than the odds ratio
